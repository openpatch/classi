import 'dart:io';

import 'package:classi/features/exams/domain/assessio_manifest.dart';
import 'package:classi/features/exams/domain/exam_calculator.dart';
import 'package:classi/features/exams/domain/exam_diff.dart';
import 'package:classi/features/exams/domain/exam_structure.dart';
import 'package:classi/features/exams/domain/grade_label_mapping.dart';
import 'package:classi/features/exams/domain/grade_scheme.dart';
import 'package:classi/shared/utils/formatting.dart';
import 'package:flutter_test/flutter_test.dart';

ImportedExam _fixture(String name) => parseAssessioManifest(
  File('test/fixtures/assessio/$name.json').readAsStringSync(),
);

/// Gives every item an id (its index + 1), as the database would.
List<ExamItem> _withIds(List<ExamItem> items) => [
  for (final (i, item) in items.indexed) item.copyWith(id: i + 1),
];

GradeScheme _schemeFromTypst(ImportedExam exam) => GradeScheme(
  thresholds: [
    for (final level in exam.scale)
      GradeThreshold(
        label: level.grade,
        minPercent: level.minPercent,
        sourceLabel: level.grade,
      ),
  ],
);

void main() {
  group('parity with assessio', () {
    // Fixtures are generated by tool/generate_assessio_fixtures.sh from the
    // typst-assessio repository; assessio computed max_points and cutoffs.
    for (final name in ['basic', 'grade-rounding', 'manifest']) {
      test('$name: maximum points and grade cutoffs match', () {
        final exam = _fixture(name);
        final calculator = ExamCalculator(
          items: _withIds(exam.items),
          meta: exam.meta,
          scheme: _schemeFromTypst(exam),
        );
        expect(calculator.maxPoints, exam.maxPoints);
        final cutoffs = calculator.scheme.cutoffs(calculator.maxPoints);
        expect([
          for (final c in cutoffs)
            (grade: c.threshold.label, points: c.cutoff.toDouble()),
        ], exam.cutoffs);
      });
    }

    test('halves round up, below halves round down', () {
      // 50% of 37 = 18.5 -> 19; 92% of 37 = 34.04 -> 34 (assessio README).
      expect(assessioCutoff(37, 50), 19);
      expect(assessioCutoff(37, 92), 34);
      expect(assessioCutoff(10, 45), 5); // 4.5 -> 5
      expect(assessioCutoff(10.5, 77), 8); // 8.085 -> 8
    });
  });

  group('manifest', () {
    test('reads kinds, keys, ids, groups and the scale', () {
      final exam = _fixture('manifest');
      expect(exam.format, 1);
      expect(exam.lang, 'de');
      expect(
        [for (final i in exam.items) (i.kind, i.scoreKey, i.maxPoints)],
        [
          (ExpectationKind.regular, '1.1', 2.0),
          (ExpectationKind.regular, '1.2', 1.0),
          (ExpectationKind.alternative, '1.3', 0.0),
          (ExpectationKind.regular, '2a.4', 1.5),
          (ExpectationKind.regular, '2b.5', 2.0),
          (ExpectationKind.elective, 'elective_3.1', 3.0),
          (ExpectationKind.elective, 'elective_4.2', 2.0),
          (ExpectationKind.additional, 'additional.1', 1.0),
        ],
      );
      expect(exam.items.first.matchKey, 'id:q1-method');
      expect(
        exam.items[1].matchKey,
        'regular|1||"lösung" angegeben, 1/2 geprüft.',
      );
      expect(exam.items.first.label, 'AFB I');
      expect(exam.meta.electiveGroups.single.countedTasks, 1);
      expect(exam.meta.taskTitles, {'1': 'Gleichungen'});
      expect([for (final l in exam.scale) l.grade], ['X', 'Y']);
      expect(
        [for (final i in exam.items) i.sortOrder],
        [0, 1, 2, 3, 4, 5, 6, 7],
      );
    });

    test('rejects unknown formats', () {
      expect(
        () => parseAssessioManifest('{"format": 99}'),
        throwsA(isA<ManifestFormatException>()),
      );
      expect(
        () => parseAssessioManifest('not json'),
        throwsA(isA<ManifestFormatException>()),
      );
    });

    test('duplicate expectations get distinct keys', () {
      final exam = parseAssessioManifest('''
        {"format": 1, "lang": "en", "expectations": [
          {"kind": "regular", "task": "1", "part": null, "key": "1.1", "points": 1, "description": "Same", "order": 1, "idx": 1},
          {"kind": "regular", "task": "1", "part": null, "key": "1.2", "points": 1, "description": "Same", "order": 1, "idx": 2}
        ]}''');
      expect(exam.items.map((i) => i.matchKey), [
        'regular|1||same',
        'regular|1||same#2',
      ]);
    });
  });

  group('calculator', () {
    late ImportedExam exam;
    late ExamCalculator calculator;
    late Map<String, int> ids;

    setUp(() {
      exam = _fixture('manifest');
      final items = _withIds(exam.items);
      ids = {for (final i in items) i.scoreKey!: i.id!};
      calculator = ExamCalculator(
        items: items,
        meta: exam.meta,
        scheme: _schemeFromTypst(exam),
      );
    });

    Map<int, double> scores(Map<String, double> byKey) => {
      for (final e in byKey.entries) ids[e.key]!: e.value,
    };

    test('counts the best elective task and the additional points', () {
      final result = calculator.compute(
        scores({
          '1.1': 2,
          '1.2': 0.5,
          '2a.4': 1.5,
          '2b.5': 1,
          'elective_3.1': 3,
          'elective_4.2': 1,
          'additional.1': 1,
        }),
      );
      // Same numbers as assessio's rendered rubric in tests/test-manifest.
      expect(result.total, 9);
      expect(result.maxPoints, 10.5);
      expect(result.grade, 'X');
      expect(result.complete, isTrue);
      expect(result.tasks['E:3']!.counted, isTrue);
      expect(result.tasks['E:4']!.counted, isFalse);
    });

    test('an elective group is complete once enough tasks are scored', () {
      final result = calculator.compute(
        scores({
          '1.1': 1,
          '1.2': 1,
          '2a.4': 1,
          '2b.5': 1,
          'elective_4.2': 2,
          'additional.1': 0,
        }),
      );
      expect(result.complete, isTrue);
      expect(result.total, 6);
    });

    test('missing points make a result incomplete but still provisional', () {
      final result = calculator.compute(scores({'1.1': 2}));
      expect(result.complete, isFalse);
      // 1.2, 2a.4, 2b.5, one elective task (1 item) and additional.1.
      expect(result.missing, 5);
      expect(result.grade, 'Y');
    });

    test('alternative expectations are never required', () {
      expect(
        calculator.items.any((i) => i.kind == ExpectationKind.alternative),
        isFalse,
      );
    });
  });

  group('grade scheme', () {
    test('picks the first threshold reached', () {
      const scheme = GradeScheme(
        thresholds: [
          GradeThreshold(label: '1', minPercent: 87),
          GradeThreshold(label: '2', minPercent: 73),
          GradeThreshold(label: '6', minPercent: 0),
        ],
      );
      expect(scheme.gradeFor(87, 100), '1');
      expect(scheme.gradeFor(86.5, 100), '2'); // cutoff 87 whole points
      expect(scheme.gradeFor(0, 100), '6');
      expect(GradeScheme.decode(scheme.encode()).sameAs(scheme), isTrue);
    });

    test('defaults follow the NRW scales by size', () {
      expect(
        defaultThresholdsFor(defaultGradeScaleEntries).map((t) => t.minPercent),
        germanGradePercents,
      );
      final points = defaultThresholdsFor(defaultPointGradeScaleEntries);
      expect(points.first.label, '15');
      expect(points.map((t) => t.minPercent), germanPointPercents);
      final extended = defaultThresholdsFor(defaultExtendedGradeScaleEntries);
      expect(extended.first.label, '1+');
      expect(extended.last.label, '6');
    });
  });

  group('grade label mapping', () {
    test('maps names, numbers and modifiers', () {
      final grades = suggestGradeLabelMapping([
        'sehr gut',
        'gut',
        'befriedigend',
        'ausreichend',
        'mangelhaft',
        'ungenügend',
      ], defaultGradeScaleEntries);
      expect(grades.values, ['1', '2', '3', '4', '5', '6']);

      final points = suggestGradeLabelMapping([
        '15 (sehr gut +)',
        '0 (ungenügend)',
      ], defaultPointGradeScaleEntries);
      expect(points, {'15 (sehr gut +)': '15', '0 (ungenügend)': '0'});

      final extended = suggestGradeLabelMapping([
        '15 (sehr gut +)',
        '14 (sehr gut)',
        '13 (sehr gut -)',
        '5 (ausreichend)',
        '4 (ausreichend -)',
      ], defaultExtendedGradeScaleEntries);
      expect(extended.values, ['1+', '1', '1-', '4', '4-']);

      final pointsByNumber = suggestGradeLabelMapping([
        '5 (ausreichend)',
      ], defaultPointGradeScaleEntries);
      expect(pointsByNumber.values, ['5']);

      final english = suggestGradeLabelMapping([
        'very good',
        'insufficient',
      ], defaultGradeScaleEntries);
      expect(english.values, ['1', '6']);
    });

    test('falls back to position, then to nothing', () {
      expect(
        suggestGradeLabelMapping(
          ['A', 'B'],
          const [
            GradeScaleEntry(label: 'x', numericValue: 1),
            GradeScaleEntry(label: 'y', numericValue: 2),
          ],
        ),
        {'A': 'x', 'B': 'y'},
      );
      expect(suggestGradeLabelMapping(['A'], defaultGradeScaleEntries), {
        'A': null,
      });
      expect(
        suggestGradeLabelMapping(
          ['A'],
          defaultGradeScaleEntries,
          previous: {'A': '3'},
        ),
        {'A': '3'},
      );
    });
  });

  group('diff and import plan', () {
    ExamItem item(
      String key,
      double points, {
      int? id,
      String task = '1',
      String? part,
      String text = 'x',
      int sort = 0,
    }) => ExamItem(
      id: id,
      matchKey: key,
      kind: ExpectationKind.regular,
      task: task,
      part: part,
      description: text,
      maxPoints: points,
      sortOrder: sort,
    );

    StructureDiff diff(List<ExamItem> before, List<ExamItem> after) =>
        diffExamStructure(
          before: before,
          after: after,
          metaBefore: const ExamStructureMeta(),
          metaAfter: const ExamStructureMeta(),
          schemeBefore: const GradeScheme(thresholds: []),
          schemeAfter: const GradeScheme(thresholds: []),
        );

    test('matches by key, then pairs leftovers in the same part', () {
      final before = [
        item('id:a', 2, id: 1, text: 'A'),
        item('regular|1||old', 1, id: 2, text: 'old', sort: 1),
        item('regular|2||gone', 1, id: 3, task: '2', text: 'gone', sort: 2),
      ];
      final after = [
        item('id:a', 1, text: 'A changed'),
        item('regular|1||new', 1, text: 'new', sort: 1),
        item('regular|3||added', 2, task: '3', text: 'added', sort: 2),
      ];
      final result = diff(before, after);
      final byType = {
        for (final type in ItemChangeType.values)
          type: result.items.where((c) => c.type == type).toList(),
      };
      expect(byType[ItemChangeType.changed]!.length, 2);
      final rewritten = byType[ItemChangeType.changed]!.firstWhere(
        (c) => c.uncertain,
      );
      expect(rewritten.before!.id, 2);
      final lowered = byType[ItemChangeType.changed]!.firstWhere(
        (c) => !c.uncertain,
      );
      expect(lowered.pointsLowered, isTrue);
      expect(byType[ItemChangeType.added]!.single.after!.task, '3');
      expect(byType[ItemChangeType.removed]!.single.before!.id, 3);
      expect(result.hasChanges, isTrue);

      final plan = ImportPlan(result);
      expect(plan.kept.keys, unorderedEquals([1, 2]));
      expect(plan.deleted.map((i) => i.id), [3]);
      expect(plan.inserted.single.task, '3');

      final split = ImportPlan(result, splitUncertain: {'regular|1||new'});
      expect(split.kept.keys, [1]);
      expect(split.deleted.map((i) => i.id), unorderedEquals([2, 3]));
      expect(split.inserted.length, 2);
    });

    test('an unchanged structure has no changes', () {
      final items = [item('id:a', 2, id: 1)];
      expect(diff(items, [item('id:a', 2)]).hasChanges, isFalse);
    });

    test('previews clamped, removed and changed grades', () {
      final before = [item('id:a', 4, id: 1), item('id:b', 2, id: 2, sort: 1)];
      final after = [item('id:a', 2)];
      final plan = ImportPlan(diff(before, after));
      const scheme = GradeScheme(
        thresholds: [
          GradeThreshold(label: 'good', minPercent: 50),
          GradeThreshold(label: 'bad', minPercent: 0),
        ],
      );
      final changes = previewGradeChanges(
        scoresByStudent: {
          7: {1: 3, 2: 0},
        },
        before: ExamCalculator(
          items: before,
          meta: const ExamStructureMeta(),
          scheme: scheme,
        ),
        after: ExamCalculator(
          items: plan.resultingItems,
          meta: const ExamStructureMeta(),
          scheme: scheme,
        ),
        plan: plan,
      );
      final change = changes.single;
      expect(change.clampedItems, 1);
      expect(change.removedScores, 1);
      expect(change.before.total, 3);
      expect(change.after.total, 2);
      expect(change.after.maxPoints, 2);
    });
  });
}
